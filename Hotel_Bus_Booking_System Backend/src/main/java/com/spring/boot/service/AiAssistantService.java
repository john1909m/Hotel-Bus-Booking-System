package com.spring.boot.service;

import com.spring.boot.dto.ai.AiResponse;
import com.spring.boot.dto.ai.AiResult;
import com.spring.boot.exception.AiRateLimitException;
import com.spring.boot.exception.AiServiceUnavailableException;
import com.spring.boot.service.ai.AiToolContext;
import com.spring.boot.service.ai.AiToolContextHolder;
import com.spring.boot.dto.ai.AiMessageDto;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.ai.chat.client.ChatClient;
import org.springframework.ai.chat.memory.ChatMemory;
import org.springframework.ai.chat.messages.MessageType;
import org.springframework.stereotype.Service;

import java.time.LocalDate;
import java.time.ZoneId;
import java.util.List;
import java.util.Set;
import java.util.stream.Collectors;

/**
 * Orchestrates the AI booking assistant (conversation with Gemini + tools).
 */
@Slf4j
@Service
@RequiredArgsConstructor
public class AiAssistantService {

    private static final ZoneId CAIRO = ZoneId.of("Africa/Cairo");
    private final ChatMemory chatMemory;
    private final ChatClient chatClient;
    private final SystemPromptService systemPromptService;

    /**
     * @param conversationId conversation id (generated by the controller if the client sent none)
     * @param message        the user's message
     * @param userId         the current user's id, resolved from the JWT (never from the client)
     */
    public AiResponse processMessage(String conversationId, String message, Long userId) {
        AiToolContext toolContext = new AiToolContext();
        toolContext.setUserId(userId);
        AiToolContextHolder.setContext(toolContext);
        try {
            // Rules live in the system prompt resource file; here we only add the current date
            String systemPrompt = systemPromptService.loadSystemPrompt()
                    + "\n\nCurrent date: " + LocalDate.now(CAIRO) + " (Africa/Cairo timezone).";

            // Memory key includes the user id so a conversation can never cross users
            String memoryKey = userId + ":" + conversationId;

            String answer = chatClient.prompt()
                    .system(systemPrompt)
                    .user(message)
                    .advisors(a -> a.param(ChatMemory.CONVERSATION_ID, memoryKey))
                    .call()
                    .content();

            if (answer == null || answer.isBlank()) {
                throw new AiServiceUnavailableException("AI service returned an empty response", null);
            }

            return buildResponse(conversationId, answer, toolContext);

        } catch (AiServiceUnavailableException | AiRateLimitException e) {
            throw e;
        } catch (Exception e) {
            log.error("AI assistant failed (userId={})", userId, e);   // never log the message text
            throw translate(e);
        } finally {
            // ThreadLocal context must always be cleared
            AiToolContextHolder.clearContext();
        }
    }

    public List<AiMessageDto> getConversation(String conversationId, Long userId) {
        String memoryKey = userId + ":" + conversationId;   // same key used in processMessage

        return chatMemory.get(memoryKey).stream()
                .filter(m -> m.getMessageType() == MessageType.USER
                        || m.getMessageType() == MessageType.ASSISTANT)
                .filter(m -> m.getText() != null && !m.getText().isBlank())
                .map(m -> new AiMessageDto(
                        m.getMessageType() == MessageType.USER ? "user" : "assistant",
                        m.getText()))
                .toList();
    }

    private AiResponse buildResponse(String conversationId, String answer, AiToolContext context) {
        List<AiResult> results = context.getResults();
        List<String> missingInformation = context.getMissingInformation();

        return new AiResponse(
                conversationId,
                answer,                          // the model's own reply
                determineIntent(results),
                results,                         // built from real tool outputs
                missingInformation,              // reported by the reportMissingInformation tool
                false,                           // drafts are created through the REST endpoint
                null
        );
    }

    /**
     * Intent = the furthest stage the tools reached in this turn.
     */
    private String determineIntent(List<AiResult> results) {
        Set<String> types = results.stream()
                .map(AiResult::type)
                .collect(Collectors.toSet());

        if (types.contains("USER_BOOKINGS")) return "BOOKING_INQUIRY";
        if (types.contains("SEAT_MAP")) return "SEAT_SELECTION";
        if (types.contains("BUS_TRIP") || types.contains("BUS_SEARCH")) return "BUS_RECOMMENDATION";
        if (types.contains("ROOM")) return "ROOM_SELECTION";
        if (types.contains("HOTEL_DETAILS")) return "HOTEL_DETAILS";
        if (types.contains("HOTEL")) return "HOTEL_SEARCH";
        return "GENERAL";
    }

    private RuntimeException translate(Exception e) {
        String chain = describeCauseChain(e).toLowerCase();

        if (chain.contains("429")
                || chain.contains("resource_exhausted")
                || chain.contains("quota")
                || chain.contains("rate limit")) {
            return new AiRateLimitException(e);
        }
        return new AiServiceUnavailableException("AI service unavailable", e);
    }

    private String describeCauseChain(Throwable t) {
        StringBuilder sb = new StringBuilder();
        int depth = 0;
        while (t != null && depth++ < 8) {
            sb.append(t.getClass().getSimpleName()).append(' ').append(t.getMessage()).append(' ');
            t = t.getCause();
        }
        return sb.toString();
    }
}